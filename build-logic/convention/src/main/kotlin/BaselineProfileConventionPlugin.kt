import androidx.baselineprofile.gradle.consumer.BaselineProfileConsumerExtension
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.kotlin.dsl.apply
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.dependencies
import java.io.File

/**
 * Ships a Baseline Profile in the library's AAR. The profile is generated by the :baselineprofile
 * module from the demo app, and each library keeps only the rules for its own classes.
 */
class BaselineProfileConventionPlugin : Plugin<Project> {
    override fun apply(project: Project) {
        project.run {
            apply(plugin = "androidx.baselineprofile")

            dependencies {
                add("baselineProfile", project(":baselineprofile"))
            }

            configure<BaselineProfileConsumerExtension> {
                filter { include("com.google.maps.android.**") }
            }

            keepOnlyOwnClasses()
        }
    }

    /**
     * The libraries share packages with each other and with the demo app (for example
     * com.google.maps.android.ktx.utils), so the package filter above can't tell them apart. After
     * the profile is copied into src, drop every rule whose class this module does not compile.
     */
    private fun Project.keepOnlyOwnClasses() {
        val classesDirs = listOf(
            "intermediates/built_in_kotlinc/release/compileReleaseKotlin/classes",
            "intermediates/javac/release/compileReleaseJavaWithJavac/classes",
        ).map { layout.buildDirectory.dir(it) }
        val profile = layout.projectDirectory.file("src/main/generated/baselineProfiles/baseline-prof.txt").asFile

        tasks.matching { it.name == "copyBaselineProfileIntoSrc" }.configureEach {
            dependsOn("compileReleaseKotlin", "compileReleaseJavaWithJavac")
            doLast {
                val roots = classesDirs.map { it.get().asFile }
                fun isOwnClass(name: String) = roots.any { File(it, "$name.class").exists() }

                val kept = profile.readLines().filter { line ->
                    val className = Regex("L([^;]+);").find(line)?.groupValues?.get(1) ?: return@filter true
                    // D8 adds classes that kotlinc and javac never write: Foo$$ExternalSyntheticLambda0
                    // for lambdas and Foo$-CC for the default methods of interface Foo.
                    val ownerClass = className.substringBefore("\$\$ExternalSynthetic").removeSuffix("\$-CC")
                    isOwnClass(className) || isOwnClass(ownerClass)
                }
                profile.writeText(kept.joinToString(separator = "\n", postfix = "\n"))
            }
        }
    }
}
